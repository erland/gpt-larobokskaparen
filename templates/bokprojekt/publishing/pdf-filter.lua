-- PDF: numrerade H1 får kompakt tvådelad kapitelstart; övriga H1 (t.ex. Inledning) blir onumrerade kapitel.
function Header(el)
  if el.level ~= 1 then return nil end
  local text = pandoc.utils.stringify(el.content)
  local number, title = text:match("^%s*(%d+)%.%s+(.+)%s*$")
  if not number then number, title = text:match("^%s*[Kk]apitel%s+(%d+):%s*(.+)%s*$") end
  if number then
    local blocks = pandoc.read(title, "markdown").blocks
    local inlines = (#blocks > 0 and blocks[1].content) or {pandoc.Str(title)}
    local title_tex = pandoc.write(pandoc.Pandoc({pandoc.Para(inlines)}), "latex"):gsub("%s+$", "")
    return pandoc.RawBlock("latex", "\\bookchapter{" .. number .. "}{" .. title_tex .. "}")
  end
  local escaped = pandoc.write(pandoc.Pandoc({pandoc.Para(el.content)}), "latex"):gsub("%s+$", "")
  return pandoc.RawBlock("latex", "\\bookfrontchapter{" .. escaped .. "}")
end


-- Non-floating figures. With Markdown -implicit_figures, a standalone image is
-- a Para/Plain with one Image. Keep illustration and its caption in one
-- unbreakable minipage at the source position (not in a float queue).
-- The image alt-text is the single caption source; no second caption is added.
local function latex_text(inlines)
  if #inlines == 0 then return "" end
  return pandoc.write(pandoc.Pandoc({pandoc.Para(inlines)}), "latex")
    :gsub("%s+$", "")
end

local function escape_path(path)
  -- Paths generated by export-book.py are local and may contain spaces.
  -- Reject characters that would break the TeX argument rather than emit
  -- unsafe or malformed LaTeX.
  if path:find("[{}\r\n]") then
    error("Otillåten sökväg i PDF-illustration: " .. path)
  end
  return "\\detokenize{" .. path .. "}"
end

local function inline_illustration(el)
  if #el.content ~= 1 or el.content[1].t ~= "Image" then return nil end
  local picture = el.content[1]
  local caption = latex_text(picture.caption)
  local command = "\\bookinlineillustration{" .. escape_path(picture.src)
    .. "}{" .. caption .. "}"
  return pandoc.RawBlock("latex", command)
end

function Para(el)
  return inline_illustration(el)
end

function Plain(el)
  return inline_illustration(el)
end
